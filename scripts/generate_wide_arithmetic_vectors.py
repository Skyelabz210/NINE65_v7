#!/usr/bin/env python3
"""Generate/check U1024 test vectors using Python's arbitrary-precision integers.

The generated Rust contains explicit expected values, not an arithmetic
implementation shared with the production limb code. No third-party modules
are needed. Run with --check to check the committed fixture without editing it.
"""

import argparse
from pathlib import Path
import random


START = "    // BEGIN PYTHON INTEGER ORACLE"
END = "    // END PYTHON INTEGER ORACLE"
MASK = (1 << 1024) - 1
WIDTHS = [
    (0, 0), (0, 1024), (1, 1024), (63, 65), (64, 64), (65, 127),
    (127, 128), (128, 128), (129, 129), (255, 256), (256, 256),
    (511, 512), (512, 512), (513, 512), (749, 274), (750, 273),
    (750, 274), (750, 275), (960, 64), (961, 64), (1000, 25),
    (1023, 2), (1024, 1023), (1024, 1024),
]
DIVISORS = [1, 2, 3, 17, (1 << 32) + 1, (1 << 63) - 1, (1 << 64) - 1]


def fixture():
    rng = random.Random(0x1024)

    def value(bits):
        return 0 if bits == 0 else rng.getrandbits(bits) | (1 << (bits - 1))

    def checked(number):
        return format(number, "x") if 0 <= number <= MASK else "overflow"

    lines = [
        START,
        "    // Generated by scripts/generate_wide_arithmetic_vectors.py; seed 0x1024.",
        "    #[test]",
        "    fn python_integer_vectors_cover_full_width_arithmetic() {",
        "        type Vector = (&'static str, &'static str, [&'static str; 5], u64, &'static str, u64);",
        "        let vectors: &[Vector] = &[",
    ]
    for index, (a_bits, b_bits) in enumerate(WIDTHS):
        a, b = value(a_bits), value(b_bits)
        divisor = DIVISORS[index % len(DIVISORS)]
        quotient, remainder = divmod(a, divisor)
        expected = [a + b, a - b, a * b, a * (b & ((1 << 64) - 1)),
                    a * (b & ((1 << 128) - 1))]
        lines += [
            f"            // Operand widths: {a_bits}, {b_bits}.",
            "            (",
            f'                "{a:x}",',
            f'                "{b:x}",',
            "                [",
            *(f'                    "{checked(number)}",' for number in expected),
            "                ],",
            f"                {divisor},",
            f'                "{quotient:x}",',
            f"                {remainder},",
            "            ),",
        ]
    lines += [
        "        ];",
        "        for &(a, b, [sum, difference, product, product64, product128], divisor, quotient, remainder) in vectors {",
        "            let (a, b) = (from_hex(a), from_hex(b));",
        "            assert_eq!(a.checked_add(b), optional_hex(sum));",
        "            assert_eq!(a.checked_sub(b), optional_hex(difference));",
        "            assert_eq!(a.checked_mul(b), optional_hex(product));",
        "            assert_eq!(b.checked_mul(a), optional_hex(product));",
        "            assert_eq!(a.checked_mul_u64(b.limbs[0]), optional_hex(product64));",
        "            let scalar = b.limbs[0] as u128 | ((b.limbs[1] as u128) << 64);",
        "            assert_eq!(a.checked_mul_u128(scalar), optional_hex(product128));",
        "            assert_eq!(a.div_mod_u64(divisor), Some((from_hex(quotient), remainder)));",
        "            assert_eq!(a.mod_u64(divisor), Some(remainder));",
        "        }",
        "    }",
        END,
    ]
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    generated = fixture()
    if args.check:
        source = (Path(__file__).resolve().parents[1]
                  / "crates/nine65/src/arithmetic/wide.rs").read_text()
        actual = source[source.index(START):source.index(END) + len(END)]
        # Rustfmt changes whitespace and trailing commas; the compiler checks
        # punctuation while this comparison pins every literal and operation.
        normalize = lambda text: "".join(text.replace(",", "").split())
        if normalize(actual) != normalize(generated):
            raise SystemExit("U1024 Python oracle fixture differs")
        print("U1024 Python integer oracle fixture matches")
    else:
        print(generated)


if __name__ == "__main__":
    main()
