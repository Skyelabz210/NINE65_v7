#!/usr/bin/env python3
"""Generate/check Q650 projection vectors using independent Python integers.

The 13-lane tuple is the expanded-route Q = 1 mod 65537^2 candidate. Expected values
are direct reductions of independently represented 650-bit integers, including
signed centered values; no CRT/rank or Rust limb implementation is reused.
"""

import argparse
import math
from pathlib import Path
import random


MAIN = [
    998244353, 985661441, 754974721, 469762049,
    576460752301785089, 576460752301391873, 576460752300015617,
    576460752298835969, 576460752298180609, 576460752293134337,
    576460752291954689, 576460752290775041, 575870995836829697,
]
# Independent projection views include a composite lane, a 61-bit lane, and a
# nearly full-u64 lane. MainOnlyBaseExt does not require prime auxiliary views.
AUX = [8, 2013265921, 2305843009213693951, 18446744073709551557]


def array(values):
    return "[" + ", ".join(str(value) for value in values) + "]"


def fixture():
    q = math.prod(MAIN)
    assert q.bit_length() == 650
    assert q % (65537 ** 2) == 1
    assert all(math.gcd(a, b) == 1 for i, a in enumerate(MAIN) for b in MAIN[i + 1:])
    rng = random.Random(0x650)
    values = [
        ("zero", 0), ("one", 1), ("q_minus_one", q - 1),
        ("floor_half", q // 2), ("ceil_half", (q + 1) // 2),
    ]
    values += [(f"seeded_{index:02}", rng.randrange(q)) for index in range(24)]
    lines = [
        "// Generated by scripts/generate_main_only_q650_vectors.py; seed 0x650.",
        "// Oracle arithmetic: Python arbitrary-precision int, X % a and (X-Q) % a.",
        "// Regenerate/check with the script; no runtime Python dependency.",
        "#[rustfmt::skip]",
        f"const Q650_MAIN: [u64; 13] = {array(MAIN)};",
        "#[rustfmt::skip]",
        f"const Q650_AUX: [u64; 4] = {array(AUX)};",
        "type Q650Vector = (&'static str, [u64; 13], [u64; 4], [u64; 4], bool);",
        "#[rustfmt::skip]",
        "const Q650_VECTORS: &[Q650Vector] = &[",
    ]
    for label, x in values:
        upper = x >= (q + 1) // 2
        centered = x - q if upper else x
        lines += [
            f"    // X = 0x{x:x}",
            "    (",
            f'        "{label}",',
            f"        {array(x % p for p in MAIN)},",
            f"        {array(x % a for a in AUX)},",
            f"        {array(centered % a for a in AUX)},",
            f"        {str(upper).lower()},",
            "    ),",
        ]
    lines += ["];", ""]
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    target = (Path(__file__).resolve().parents[1] /
              "crates/nine65/tests/fixtures/main_only_q650_vectors.rs")
    generated = fixture()
    if args.check:
        if target.read_text() != generated:
            raise SystemExit(f"stale Q650 integer vectors: {target}")
        print("Q650 Python integer oracle: 29 canonical and centered vectors match")
    else:
        target.write_text(generated)
        print(f"wrote {target}")


if __name__ == "__main__":
    main()
